-- 1. Auto-create Profile on auth.users insert
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  insert into public.profiles (id, full_name, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    coalesce(new.raw_user_meta_data->>'phone', ''),
    'customer'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 2. Trigger: Block unauthorized role changes
-- Only postgres, service_role, or supabase_admin can elevate a user to admin.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if old.role is distinct from new.role then
    if current_user not in ('postgres', 'service_role', 'supabase_admin') then
      raise exception 'Security Violation: User role modification is strictly prohibited.';
    end if;
  end if;
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_protect_profile_role on public.profiles;
create trigger trg_protect_profile_role
  before update on public.profiles
  for each row execute function public.protect_profile_role();

-- Column-level grants: Authenticated customers can only update full_name and phone
revoke update on public.profiles from public, anon, authenticated;
grant update (full_name, phone) on public.profiles to authenticated;
grant select on public.profiles to authenticated, anon;

-- 3. Trigger: Automatically restore stock when order is cancelled
-- Aggregates stock restoration per product, blocks moving out of 'cancelled', prevents cancelling shipped/delivered orders, returns coupon usage only if discount was given.
create or replace function public.restore_stock_on_cancel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Block moving an order out of 'cancelled'
  if old.status = 'cancelled' and new.status <> 'cancelled' then
    raise exception 'Cannot change status of a cancelled order.';
  end if;

  -- Block cancelling already shipped or delivered orders
  if old.status in ('shipped', 'delivered') and new.status = 'cancelled' then
    raise exception 'Cannot cancel order "%" after it has been shipped or delivered. Please process via showroom return.', old.order_no;
  end if;

  -- Transitioning into 'cancelled'
  if new.status = 'cancelled' and old.status <> 'cancelled' then
    -- Restore product stock aggregated per product_id
    update public.products p
    set stock = p.stock + agg.total_qty
    from (
      select product_id, sum(qty) as total_qty
      from public.order_items
      where order_id = new.id and product_id is not null
      group by product_id
    ) agg
    where p.id = agg.product_id;

    -- Return coupon usage ONLY if the order claimed an actual discount
    if old.discount_inr > 0 and old.coupon_code is not null and trim(old.coupon_code) <> '' then
      update public.coupons
      set used_count = greatest(0, used_count - 1)
      where code = upper(trim(old.coupon_code));
    end if;
  end if;

  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_restore_stock_on_cancel on public.orders;
create trigger trg_restore_stock_on_cancel
  before update on public.orders
  for each row execute function public.restore_stock_on_cancel();

-- 4. Audit Log Triggers
-- Only write rows when acting user is admin, ignore no-op updates to eliminate noise, and strip all customer personal details.
create or replace function public.audit_log_trigger()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  actor_id uuid;
  clean_old jsonb;
  clean_new jsonb;
begin
  -- Only write rows when the acting user is an admin
  if not public.is_admin() then
    return coalesce(NEW, OLD);
  end if;

  actor_id := auth.uid();

  -- Specialized handling for orders: eliminate noise & strip all customer PII
  if TG_TABLE_NAME = 'orders' then
    -- Skip no-op / timestamp-only updates (reduces audit log noise)
    if TG_OP = 'UPDATE' and
       OLD.status is not distinct from NEW.status and
       OLD.payment_status is not distinct from NEW.payment_status and
       OLD.tracking_note is not distinct from NEW.tracking_note then
      return coalesce(NEW, OLD);
    end if;

    -- Scrub ALL customer personal details; record only operational fulfillment fields
    if TG_OP in ('UPDATE', 'DELETE') then
      clean_old := jsonb_build_object(
        'order_no', OLD.order_no,
        'status', OLD.status,
        'payment_status', OLD.payment_status,
        'tracking_note', OLD.tracking_note
      );
    end if;

    if TG_OP in ('INSERT', 'UPDATE') then
      clean_new := jsonb_build_object(
        'order_no', NEW.order_no,
        'status', NEW.status,
        'payment_status', NEW.payment_status,
        'tracking_note', NEW.tracking_note
      );
    end if;
  else
    -- For products, coupons, settings: skip if no actual column changes
    if TG_OP = 'UPDATE' and to_jsonb(OLD) - 'updated_at' = to_jsonb(NEW) - 'updated_at' then
      return coalesce(NEW, OLD);
    end if;

    if TG_OP in ('UPDATE', 'DELETE') then
      clean_old := to_jsonb(OLD) - 'customer_phone' - 'customer_email' - 'address_line1' - 'city' - 'state' - 'pincode' - 'phone' - 'full_name' - 'customer_name';
    end if;

    if TG_OP in ('INSERT', 'UPDATE') then
      clean_new := to_jsonb(NEW) - 'customer_phone' - 'customer_email' - 'address_line1' - 'city' - 'state' - 'pincode' - 'phone' - 'full_name' - 'customer_name';
    end if;
  end if;

  insert into public.admin_audit_log (who, target_table, action, old_data, new_data)
  values (
    actor_id,
    TG_TABLE_NAME,
    TG_OP,
    clean_old,
    clean_new
  );
  return coalesce(NEW, OLD);
end;
$$;

drop trigger if exists audit_products on public.products;
create trigger audit_products after insert or update or delete on public.products
for each row execute function public.audit_log_trigger();

drop trigger if exists audit_coupons on public.coupons;
create trigger audit_coupons after insert or update or delete on public.coupons
for each row execute function public.audit_log_trigger();

-- Only audit staff UPDATE on orders (customer order placements are already in orders; no insert noise)
drop trigger if exists audit_orders on public.orders;
create trigger audit_orders after update on public.orders
for each row execute function public.audit_log_trigger();

drop trigger if exists audit_settings on public.settings;
create trigger audit_settings after insert or update or delete on public.settings
for each row execute function public.audit_log_trigger();

