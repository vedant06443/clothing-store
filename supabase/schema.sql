-- 1. Helper: Check if current authenticated user is an admin
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public, auth
stable
as $$
  select coalesce(
    (select role = 'admin' from public.profiles where id = auth.uid()),
    false
  );
$$;

-- 2. Validate Coupon Function (Never reveals other coupons)
create or replace function public.validate_coupon(
  coupon_code text,
  items jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  c_row record;
  cart_item jsonb;
  subtotal integer := 0;
  category_subtotal integer := 0;
  prod_row record;
  discount integer := 0;
  normalized_code text;
begin
  if coupon_code is null or length(trim(coupon_code)) = 0 then
    return jsonb_build_object('valid', false, 'error', 'Coupon code cannot be empty.');
  end if;

  if length(trim(coupon_code)) > 50 then
    return jsonb_build_object('valid', false, 'error', 'Coupon code exceeds maximum permitted length.');
  end if;

  normalized_code := upper(trim(coupon_code));

  select * into c_row from public.coupons where code = normalized_code;
  if not found or not c_row.is_active then
    return jsonb_build_object('valid', false, 'error', 'Invalid or inactive coupon code.');
  end if;

  if c_row.starts_at > now() then
    return jsonb_build_object('valid', false, 'error', 'Coupon offer has not started yet.');
  end if;

  if c_row.ends_at is not null and c_row.ends_at < now() then
    return jsonb_build_object('valid', false, 'error', 'Coupon code has expired.');
  end if;

  if c_row.max_uses is not null and c_row.used_count >= c_row.max_uses then
    return jsonb_build_object('valid', false, 'error', 'Coupon usage limit has been reached.');
  end if;

  -- Calculate subtotal directly from database prices for cart items
  for cart_item in select * from jsonb_array_elements(items)
  loop
    select p.price_inr, c.slug as cat_slug into prod_row
    from public.products p
    left join public.categories c on c.id = p.category_id
    where p.id = (cart_item->>'id')::bigint and p.is_active = true;

    if found then
      subtotal := subtotal + (prod_row.price_inr * (cart_item->>'qty')::integer);
      if cardinality(c_row.category_slugs) = 0 or prod_row.cat_slug = any(c_row.category_slugs) then
        category_subtotal := category_subtotal + (prod_row.price_inr * (cart_item->>'qty')::integer);
      end if;
    end if;
  end loop;

  if subtotal < c_row.min_order_inr then
    return jsonb_build_object(
      'valid', false,
      'error', 'Minimum order amount for ' || c_row.code || ' is ₹' || c_row.min_order_inr || '.'
    );
  end if;

  if cardinality(c_row.category_slugs) > 0 and category_subtotal = 0 then
    return jsonb_build_object(
      'valid', false,
      'error', 'Coupon ' || c_row.code || ' is not applicable to the items in your cart.'
    );
  end if;

  -- Calculate discount based on eligible category subtotal
  if c_row.type = 'percent' then
    discount := round((category_subtotal * c_row.value)::numeric / 100.0);
  else
    discount := c_row.value;
  end if;

  if discount > category_subtotal then
    discount := category_subtotal;
  end if;

  return jsonb_build_object(
    'valid', true,
    'code', c_row.code,
    'type', c_row.type,
    'value', c_row.value,
    'discount_inr', discount,
    'min_order_inr', c_row.min_order_inr
  );
end;
$$;

-- 3. Atomic Order Placement Function
create or replace function public.place_order(
  customer jsonb,
  items jsonb,
  coupon text default null,
  payment_method text default 'cod'
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  c_name text;
  c_phone text;
  c_email text;
  c_address text;
  c_city text;
  c_state text;
  c_pincode text;
  c_pay_method public.payment_method;
  
  recent_orders_count integer;
  order_subtotal integer := 0;
  order_discount integer := 0;
  order_shipping integer := 0;
  order_total integer := 0;
  
  threshold_val integer := 1499;
  fee_val integer := 0;
  
  new_order_id uuid;
  gen_order_no text;
  date_part text;
  random_part text;
  
  cart_item jsonb;
  item_prod_id bigint;
  item_qty integer;
  item_size text;
  
  p_record record;
  c_record record;
  item_total integer;
  coupon_res jsonb;
  authenticated_uid uuid;
  distinct_items_count integer;
  locked_items_count integer;
begin
  -- 1. Validate Payment Method: Explicitly block 'online' until Phase 5 gateway is deployed
  if payment_method = 'online' then
    raise exception 'Online payments are currently disabled. Please select Cash on Delivery (COD) or WhatsApp.';
  end if;

  if payment_method not in ('cod', 'whatsapp') then
    raise exception 'Invalid payment method. Only "cod" or "whatsapp" are accepted.';
  end if;
  c_pay_method := payment_method::public.payment_method;

  -- 2. Cart line count and duplicate product line validation
  if items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then
    raise exception 'Your shopping bag is empty.';
  end if;

  if jsonb_array_length(items) > 50 then
    raise exception 'Cart exceeds maximum limit of 50 item lines.';
  end if;

  -- Block duplicate product lines with identical product ID and size
  if exists (
    select 1
    from jsonb_array_elements(items) elem
    group by (elem->>'id')::bigint, coalesce(trim(elem->>'size'), 'Free Size')
    having count(*) > 1
  ) then
    raise exception 'Duplicate product lines detected in cart. Please consolidate quantities for the same item and size.';
  end if;

  -- 3. Extract & Validate customer fields with strict length caps
  c_name := trim(coalesce(customer->>'name', ''));
  c_phone := regexp_replace(coalesce(customer->>'phone', ''), '[^0-9]', '', 'g');
  c_email := lower(trim(coalesce(customer->>'email', '')));
  c_address := trim(coalesce(customer->>'address', ''));
  c_city := trim(coalesce(customer->>'city', ''));
  c_state := trim(coalesce(customer->>'state', 'Maharashtra'));
  c_pincode := regexp_replace(coalesce(customer->>'pincode', ''), '[^0-9]', '', 'g');

  if length(c_name) < 2 or length(c_name) > 100 then
    raise exception 'Please provide your full name (between 2 and 100 characters).';
  end if;

  if length(c_phone) <> 10 then
    raise exception 'Please provide a valid 10-digit Indian mobile number.';
  end if;

  if length(c_email) > 255 or c_email !~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$' then
    raise exception 'Please provide a valid email address (maximum 255 characters).';
  end if;

  if length(c_address) < 5 or length(c_address) > 300 then
    raise exception 'Please provide a complete delivery address (between 5 and 300 characters).';
  end if;

  if length(c_city) < 2 or length(c_city) > 60 then
    raise exception 'Please provide your delivery city (between 2 and 60 characters).';
  end if;

  if length(c_state) < 2 or length(c_state) > 50 then
    raise exception 'Please provide your delivery state (between 2 and 50 characters).';
  end if;

  if length(c_pincode) <> 6 then
    raise exception 'Please provide a valid 6-digit Indian PIN code.';
  end if;

  if coupon is not null and length(trim(coupon)) > 50 then
    raise exception 'Coupon code exceeds maximum permitted length of 50 characters.';
  end if;

  -- 4. Anti-Abuse Rate Limit: At most 5 orders per phone per hour
  select count(*) into recent_orders_count
  from public.orders
  where customer_phone = c_phone
    and created_at > (now() - interval '1 hour');

  if recent_orders_count >= 5 then
    raise exception 'Order limit reached for this phone number (max 5 orders/hour). Please contact our showroom directly on WhatsApp for assistance.';
  end if;

  -- 5. Validate Line Items: sizes and quantities length
  for cart_item in select * from jsonb_array_elements(items)
  loop
    item_qty := coalesce((cart_item->>'qty')::integer, 1);
    item_size := coalesce(cart_item->>'size', 'Free Size');

    if item_qty < 1 or item_qty > 10 then
      raise exception 'Quantity for each item line must be between 1 and 10.';
    end if;

    if length(item_size) > 20 then
      raise exception 'Size identifier "%" exceeds maximum length of 20 characters.', item_size;
    end if;
  end loop;

  -- 6. Lock products in ASCENDING id order, enforce per-product max quantity (10), and check live stock
  select count(distinct (elem->>'id')::bigint) into distinct_items_count
  from jsonb_array_elements(items) elem;

  locked_items_count := 0;

  for p_record in
    select p.*, agg.total_qty
    from public.products p
    join (
      select (elem->>'id')::bigint as p_id,
             sum(coalesce((elem->>'qty')::integer, 1)) as total_qty
      from jsonb_array_elements(items) elem
      group by (elem->>'id')::bigint
    ) agg on agg.p_id = p.id
    order by p.id asc
    for update of p
  loop
    locked_items_count := locked_items_count + 1;

    if not p_record.is_active then
      raise exception 'Product "%" is no longer available.', p_record.name;
    end if;

    if p_record.total_qty > 10 then
      raise exception 'Maximum allowed quantity per product is 10 (requested % for "%").',
        p_record.total_qty, p_record.name;
    end if;

    if p_record.stock < p_record.total_qty then
      raise exception 'Sorry, "%" is out of stock (only % left, requested %).',
        p_record.name, p_record.stock, p_record.total_qty;
    end if;
  end loop;

  if locked_items_count <> distinct_items_count then
    raise exception 'One or more items in your cart could not be found in our catalog.';
  end if;

  -- 7. Validate that all requested sizes exist in product.sizes
  for cart_item in select * from jsonb_array_elements(items)
  loop
    item_prod_id := (cart_item->>'id')::bigint;
    item_size := coalesce(cart_item->>'size', 'Free Size');

    select sizes, name into p_record
    from public.products
    where id = item_prod_id;

    if p_record.sizes is not null and cardinality(p_record.sizes) > 0 then
      if not (item_size = any(p_record.sizes)) then
        raise exception 'Size "%" is not valid for product "%". Available sizes: %',
          item_size, p_record.name, array_to_string(p_record.sizes, ', ');
      end if;
    end if;
  end loop;

  -- 8. Compute order subtotal directly from database prices
  for cart_item in select * from jsonb_array_elements(items)
  loop
    item_prod_id := (cart_item->>'id')::bigint;
    item_qty := coalesce((cart_item->>'qty')::integer, 1);

    select price_inr into p_record
    from public.products
    where id = item_prod_id;

    order_subtotal := order_subtotal + (p_record.price_inr * item_qty);
  end loop;

  -- 9. Read settings from JSONB objects with COALESCE default fallbacks
  select coalesce(
    (value->>'free_shipping_threshold')::integer,
    (value->>'value')::integer
  ) into threshold_val
  from public.settings
  where key = 'free_shipping_threshold';
  threshold_val := coalesce(threshold_val, 1499);

  select coalesce(
    (value->>'shipping_fee')::integer,
    (value->>'value')::integer
  ) into fee_val
  from public.settings
  where key = 'shipping_fee';
  fee_val := coalesce(fee_val, 0);

  -- Free shipping applies when subtotal (before coupon discount) >= threshold_val
  if order_subtotal >= threshold_val then
    order_shipping := 0;
  else
    order_shipping := fee_val;
  end if;

  -- 10. Validate & Apply Coupon with row locking (eliminates race condition on max_uses)
  if coupon is not null and trim(coupon) <> '' then
    -- Lock coupon row for update immediately
    select * into c_record
    from public.coupons
    where code = upper(trim(coupon))
    for update;

    if not found or not c_record.is_active then
      raise exception 'Coupon code "%" is invalid or inactive.', upper(trim(coupon));
    end if;

    if c_record.starts_at > now() then
      raise exception 'Coupon offer "%" has not started yet.', c_record.code;
    end if;

    if c_record.ends_at is not null and c_record.ends_at < now() then
      raise exception 'Coupon code "%" has expired.', c_record.code;
    end if;

    if c_record.max_uses is not null and c_record.used_count >= c_record.max_uses then
      raise exception 'Coupon usage limit has been reached for code "%".', c_record.code;
    end if;

    coupon_res := public.validate_coupon(coupon, items);
    if (coupon_res->>'valid')::boolean = true then
      order_discount := (coupon_res->>'discount_inr')::integer;
    else
      raise exception '%', coupon_res->>'error';
    end if;
  end if;

  order_total := order_subtotal - order_discount + order_shipping;
  if order_total < 0 then
    order_total := 0;
  end if;

  -- 11. Atomic Coupon Usage Increment (under existing row lock)
  if order_discount > 0 and c_record.code is not null then
    update public.coupons
    set used_count = used_count + 1
    where code = c_record.code;
  end if;

  -- 12. Generate Unguessable Order Number: SYG-YYMMDD- plus 12 CSPRNG hex characters (48 bits entropy)
  date_part := to_char(now() at time zone 'Asia/Kolkata', 'YYMMDD');
  loop
    random_part := upper(encode(gen_random_bytes(6), 'hex'));
    gen_order_no := 'SYG-' || date_part || '-' || random_part;
    exit when not exists (select 1 from public.orders where order_no = gen_order_no);
  end loop;

  authenticated_uid := auth.uid();

  -- 13. Insert Order Record
  insert into public.orders (
    order_no,
    user_id,
    customer_name,
    customer_phone,
    customer_email,
    address_line1,
    city,
    state,
    pincode,
    payment_method,
    payment_status,
    status,
    subtotal_inr,
    discount_inr,
    shipping_inr,
    total_inr,
    coupon_code
  ) values (
    gen_order_no,
    authenticated_uid,
    c_name,
    c_phone,
    c_email,
    c_address,
    c_city,
    c_state,
    c_pincode,
    c_pay_method,
    'pending',
    'placed',
    order_subtotal,
    order_discount,
    order_shipping,
    order_total,
    upper(trim(coalesce(coupon, '')))
  ) returning id into new_order_id;

  -- 14. Insert Order Items & Decrement Stock
  for cart_item in select * from jsonb_array_elements(items)
  loop
    item_prod_id := (cart_item->>'id')::bigint;
    item_qty := coalesce((cart_item->>'qty')::integer, 1);
    item_size := coalesce(cart_item->>'size', 'Free Size');

    select * into p_record from public.products where id = item_prod_id;
    item_total := p_record.price_inr * item_qty;

    insert into public.order_items (
      order_id,
      product_id,
      name_snapshot,
      size,
      qty,
      unit_price_inr,
      total_price_inr,
      image_snapshot
    ) values (
      new_order_id,
      item_prod_id,
      p_record.name,
      item_size,
      item_qty,
      p_record.price_inr,
      item_total,
      case when cardinality(p_record.image_paths) > 0 then p_record.image_paths[1] else null end
    );

    -- Decrement inventory
    update public.products
    set stock = stock - item_qty
    where id = item_prod_id;
  end loop;

  return jsonb_build_object(
    'success', true,
    'order_no', gen_order_no,
    'order_id', new_order_id,
    'subtotal_inr', order_subtotal,
    'discount_inr', order_discount,
    'shipping_inr', order_shipping,
    'total_inr', order_total
  );
end;
$$;

-- 4. Guest Order Tracking Function (Requires matching order_no and phone, enforces input bounds)
create or replace function public.get_order_status(
  order_no text,
  phone text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  o_row record;
  items_arr jsonb;
begin
  if order_no is null or length(trim(order_no)) = 0 or length(order_no) > 50 or
     phone is null or length(trim(phone)) = 0 or length(phone) > 25 then
    return jsonb_build_object('found', false);
  end if;

  select * into o_row from public.orders
  where upper(trim(orders.order_no)) = upper(trim(get_order_status.order_no))
    and regexp_replace(orders.customer_phone, '[^0-9]', '', 'g') = regexp_replace(get_order_status.phone, '[^0-9]', '', 'g');

  if not found then
    return jsonb_build_object('found', false);
  end if;

  select jsonb_agg(jsonb_build_object(
    'name', name_snapshot,
    'size', size,
    'qty', qty,
    'unit_price_inr', unit_price_inr,
    'total_price_inr', total_price_inr,
    'image', image_snapshot
  )) into items_arr
  from public.order_items
  where order_id = o_row.id;

  return jsonb_build_object(
    'found', true,
    'order_no', o_row.order_no,
    'status', o_row.status,
    'payment_status', o_row.payment_status,
    'payment_method', o_row.payment_method,
    'tracking_note', o_row.tracking_note,
    'created_at', o_row.created_at,
    'customer_name', o_row.customer_name,
    'total_inr', o_row.total_inr,
    'items', coalesce(items_arr, '[]'::jsonb)
  );
end;
$$;

