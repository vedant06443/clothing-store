exception
  when duplicate_object then null;
end $$;

do $$ begin
  create type public.order_status as enum ('placed', 'confirmed', 'shipped', 'delivered', 'cancelled');
exception
  when duplicate_object then null;
end $$;

do $$ begin
  create type public.payment_status as enum ('pending', 'paid', 'refunded', 'failed');
exception
  when duplicate_object then null;
end $$;

do $$ begin
  create type public.payment_method as enum ('cod', 'whatsapp', 'online');
exception
  when duplicate_object then null;
end $$;

do $$ begin
  create type public.coupon_type as enum ('percent', 'flat');
exception
  when duplicate_object then null;
end $$;

-- 3. PROFILES TABLE
-- Automatically mirrors auth.users. Role can only be changed by postgres/service role.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role public.user_role not null default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 4. ADDRESSES TABLE
create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  label text not null default 'Home',
  line1 text not null,
  city text not null,
  state text not null default 'Maharashtra',
  pincode text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

-- 5. CATEGORIES TABLE
create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  name text not null,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

-- 6. PRODUCTS TABLE
-- price_inr and mrp_inr are integers.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  category_id uuid references public.categories(id) on delete set null,
  description text not null default '',
  price_inr integer not null check (price_inr >= 0),
  mrp_inr integer not null check (mrp_inr >= price_inr),
  sizes text[] not null default '{"Free Size"}',
  stock integer not null default 0 check (stock >= 0),
  image_paths text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 7. COUPONS TABLE
create table if not exists public.coupons (
  code text primary key,
  type public.coupon_type not null,
  value integer not null check (value > 0),
  min_order_inr integer not null default 0 check (min_order_inr >= 0),
  category_slugs text[] not null default '{}',
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  max_uses integer check (max_uses is null or max_uses > 0),
  used_count integer not null default 0 check (used_count >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 8. SETTINGS TABLE
create table if not exists public.settings (
  key text primary key,
  value jsonb not null,
  description text,
  updated_at timestamptz not null default now()
);

-- 9. ORDERS TABLE
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no text unique not null,
  user_id uuid references public.profiles(id) on delete set null,
  customer_name text not null check (length(customer_name) between 2 and 100),
  customer_phone text not null check (length(customer_phone) between 10 and 20),
  customer_email text not null check (length(customer_email) <= 255),
  address_line1 text not null check (length(address_line1) between 5 and 300),
  city text not null check (length(city) between 2 and 60),
  state text not null check (length(state) between 2 and 50),
  pincode text not null check (length(pincode) between 5 and 10),
  payment_method public.payment_method not null check (payment_method in ('cod', 'whatsapp')),
  payment_status public.payment_status not null default 'pending',
  status public.order_status not null default 'placed',
  subtotal_inr integer not null check (subtotal_inr >= 0),
  discount_inr integer not null default 0 check (discount_inr >= 0),
  shipping_inr integer not null default 0 check (shipping_inr >= 0),
  total_inr integer not null check (total_inr >= 0),
  coupon_code text check (coupon_code is null or length(coupon_code) <= 50),
  tracking_note text check (tracking_note is null or length(tracking_note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 10. ORDER ITEMS TABLE
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  name_snapshot text not null,
  size text not null default 'Free Size',
  qty integer not null check (qty > 0),
  unit_price_inr integer not null check (unit_price_inr >= 0),
  total_price_inr integer not null check (total_price_inr >= 0),
  image_snapshot text
);

-- 11. ADMIN AUDIT LOG TABLE
create table if not exists public.admin_audit_log (
  id uuid primary key default gen_random_uuid(),
  who uuid references auth.users(id) on delete set null,
  target_table text not null,
  action text not null,
  old_data jsonb,
  new_data jsonb,
  at timestamptz not null default now()
);

